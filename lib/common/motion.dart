import 'package:material_ui/material_ui.dart';

/// Движение Mgla — «рез».
///
/// Дизайн-код владельца 12-09, записанный дословно: «мгла, холод, острота, металл, катана».
/// Из этого следует ровно одно требование к анимации: НОЛЬ ОТСКОКА И ПРУЖИН. Отскок — это
/// мягкость и игрушечность, у катаны и у пикапа её нет. Движение входит быстро и останавливается
/// насухо, как рез.
///
/// ПОЧЕМУ ОДНА КРИВАЯ НА ВСЁ ПРИЛОЖЕНИЕ. Разные кривые в разных местах человек не опознаёт как
/// разнообразие — он читает это как несобранность. Один акцент, одна кривая, три длительности.
///
/// ЧТО ЭТО ЗАМЕНИЛО: back-кривые апстрима в девяти местах (кнопка подключения, всплывающие
/// панели, переходы). Они ПЕРЕЛЕТАЮТ цель и возвращаются — ровно тот отскок, который
/// дизайн-код запрещает. Имена тех кривых здесь не пишутся намеренно: сплошная замена по lib/
/// однажды уже прошлась по этому самому файлу и переписала строку, которая их называла.
class MglaMotion {
  MglaMotion._();

  /// Единственная кривая системы. Совпадает с cubic-bezier(.16,.84,.28,1) на сайте mgla.app —
  /// приложение и сайт обязаны двигаться одинаково, иначе это два разных продукта.
  static const Curve cut = Cubic(0.16, 0.84, 0.28, 1.0);

  /// Обратная — для уходящего элемента. Не «другая кривая», а та же, прочитанная с конца.
  static final Curve cutOut = cut.flipped;

  /// Отклик на нажатие: человек должен увидеть ответ, а не анимацию.
  static const Duration fast = Duration(milliseconds: 110);

  /// Основная длительность: появление, смена состояния, раскрытие.
  static const Duration base = Duration(milliseconds: 240);

  /// Крупные перестроения экрана. Дольше — уже заметно как задержка.
  static const Duration slow = Duration(milliseconds: 420);
}
